"""
V3: Rhizome Builder Agent — Core Pipeline (The Muscle)
Classifies relationships via LLM and persists them to Neo4j using the V3
three-edge-type schema:
  - Constructive (thin, solid): extends, uses_method_from, builds_on
  - Critical (thick, dashed): contradicts, critiques, problematizes
  - Rhizomatic (neon, pulsing): ontological_rupture — carries axiom metadata

Neo4j is OPTIONAL. If not configured, the builder logs the edges without
persisting them and returns a skip result. The in-memory RelationshipGraph
(generated by relationship_mapper.py) always runs regardless of Neo4j status.
"""
import json
from models import (
    RelationshipGraph, GraphEdge, GraphNode,
    RhizomePersistResult, RuptureOutput,
)
from config import settings
from pipeline import logger, ollama_chat, record_tokens

# ─── Edge Classification Prompt ──────────────────────────────────────────────

EDGE_CLASSIFY_SYSTEM = """You are the Rhizome Builder Agent. You receive a list of edges from a relationship graph
(each with source, target, and relationship label) and you must classify each edge into one of three types:

- constructive: The source paper extends, builds on, or borrows methods from the target.
  Use for: extends, uses_method_from, builds_on, applies, operationalizes

- critical: The source paper contradicts, critiques, or problematizes the target.
  Use for: contradicts, critiques, problematizes, challenges, questions

- rhizomatic: The source paper represents a paradigm rupture relative to the target —
  it introduces an entirely different ontological or epistemological frame.
  For rhizomatic edges you MUST also provide:
  - axiom_target: the dominant assumption the source paper dismantles
  - counter_axiom: the heterodox perspective introduced
  - rupture_vector: one of Methodological | Epistemological | Ontological

OUTPUT FORMAT — Return ONLY valid JSON:
{
  "classified_edges": [
    {
      "source": "node_id",
      "target": "node_id",
      "relationship": "original relationship label",
      "edge_type": "constructive | critical | rhizomatic",
      "axiom_target": null,
      "counter_axiom": null,
      "rupture_vector": null
    }
  ]
}
"""


async def _classify_edges(edges: list[GraphEdge]) -> list[GraphEdge]:
    """Use LLM to classify edges into constructive/critical/rhizomatic types."""
    if not edges:
        return edges

    edge_payload = json.dumps(
        [
            {
                "source": e.source,
                "target": e.target,
                "relationship": e.relationship,
                "intensity": e.intensity,
            }
            for e in edges
        ],
        ensure_ascii=False,
    )

    try:
        from pipeline import clean_json
        raw = await ollama_chat(
            messages=[
                {"role": "system", "content": EDGE_CLASSIFY_SYSTEM},
                {"role": "user", "content": f"Classify these edges:\n{edge_payload}"},
            ],
            label="RhizomeBuilder",
        )
        record_tokens(raw)
        data = clean_json(raw["message"]["content"])
        classified = data.get("classified_edges", [])

        classified_map = {(c["source"], c["target"]): c for c in classified}
        updated = []
        for edge in edges:
            key = (edge.source, edge.target)
            cls = classified_map.get(key, {})
            updated.append(
                GraphEdge(
                    source=edge.source,
                    target=edge.target,
                    relationship=edge.relationship,
                    intensity=edge.intensity,
                    edge_type=cls.get("edge_type", "constructive"),
                    axiom_target=cls.get("axiom_target"),
                    counter_axiom=cls.get("counter_axiom"),
                    rupture_vector=cls.get("rupture_vector"),
                )
            )
        return updated

    except Exception as exc:
        logger.warning(f"Edge classification LLM failed ({exc}), using default 'constructive'.")
        return edges


# ─── Neo4j Persistence ────────────────────────────────────────────────────────

async def _persist_to_neo4j(graph: RelationshipGraph) -> RhizomePersistResult:
    """Write nodes and classified edges to Neo4j via the database client."""
    try:
        from database.neo4j_client import get_neo4j_client
        client = get_neo4j_client()
        if client is None:
            return RhizomePersistResult(
                neo4j_enabled=False,
                message="Neo4j client not initialized.",
            )

        constructive = critical = rhizomatic = 0

        with client.session() as session:
            # Upsert nodes
            for node in graph.nodes:
                session.run(
                    """
                    MERGE (p:Paper {id: $id})
                    SET p.label = $label,
                        p.type = $type,
                        p.importance = $importance,
                        p.description = $description,
                        p.is_rupture_node = $is_rupture_node,
                        p.axiom_dismantled = $axiom_dismantled
                    """,
                    id=node.id,
                    label=node.label,
                    type=node.type,
                    importance=node.importance,
                    description=node.description,
                    is_rupture_node=node.is_rupture_node,
                    axiom_dismantled=node.axiom_dismantled,
                )

            # Create classified edges
            for edge in graph.edges:
                if edge.edge_type == "constructive":
                    session.run(
                        """
                        MATCH (a:Paper {id: $src}), (b:Paper {id: $tgt})
                        MERGE (a)-[r:CONSTRUCTIVE {relationship: $rel}]->(b)
                        SET r.intensity = $intensity
                        """,
                        src=edge.source, tgt=edge.target,
                        rel=edge.relationship, intensity=edge.intensity,
                    )
                    constructive += 1

                elif edge.edge_type == "critical":
                    session.run(
                        """
                        MATCH (a:Paper {id: $src}), (b:Paper {id: $tgt})
                        MERGE (a)-[r:CRITICAL {relationship: $rel}]->(b)
                        SET r.intensity = $intensity
                        """,
                        src=edge.source, tgt=edge.target,
                        rel=edge.relationship, intensity=edge.intensity,
                    )
                    critical += 1

                elif edge.edge_type == "rhizomatic":
                    session.run(
                        """
                        MATCH (a:Paper {id: $src}), (b:Paper {id: $tgt})
                        MERGE (a)-[r:RHIZOMATIC]->(b)
                        SET r.axiom_target = $axiom_target,
                            r.counter_axiom = $counter_axiom,
                            r.rupture_vector = $rupture_vector,
                            r.intensity = $intensity
                        """,
                        src=edge.source, tgt=edge.target,
                        axiom_target=edge.axiom_target or "",
                        counter_axiom=edge.counter_axiom or "",
                        rupture_vector=edge.rupture_vector or "Epistemological",
                        intensity=edge.intensity,
                    )
                    rhizomatic += 1

        return RhizomePersistResult(
            nodes_created=len(graph.nodes),
            constructive_edges=constructive,
            critical_edges=critical,
            rhizomatic_edges=rhizomatic,
            neo4j_enabled=True,
            message=f"Persisted {len(graph.nodes)} nodes and {constructive+critical+rhizomatic} edges to Neo4j.",
        )

    except ImportError:
        return RhizomePersistResult(
            neo4j_enabled=False,
            message="Neo4j driver (neo4j package) not installed.",
        )
    except Exception as exc:
        logger.error(f"Neo4j persistence failed: {exc}")
        return RhizomePersistResult(
            neo4j_enabled=True,
            message=f"Neo4j write failed: {exc}",
        )


# ─── Graph Centralization Detection ──────────────────────────────────────────

def _detect_centralization(
    graph: RelationshipGraph,
    threshold: float = 0.40,
    top_n: int = 3,
) -> tuple[bool, list[str], float]:
    """
    Detect whether the graph is dominated by a small number of nodes.
    Returns (is_centralized, central_node_ids, centralization_ratio).

    Logic: if the top-N nodes by degree hold ≥ threshold fraction of all
    edge endpoints, the graph is considered centralized and a rupture is
    warranted on the next traversal.
    """
    if not graph.edges:
        return False, [], 0.0

    degree: dict[str, int] = {}
    for edge in graph.edges:
        degree[edge.source] = degree.get(edge.source, 0) + 1
        degree[edge.target] = degree.get(edge.target, 0) + 1

    total = sum(degree.values())
    if total == 0:
        return False, [], 0.0

    sorted_nodes = sorted(degree.items(), key=lambda x: x[1], reverse=True)
    top_nodes = sorted_nodes[:top_n]
    top_degree_sum = sum(d for _, d in top_nodes)
    ratio = top_degree_sum / total

    is_centralized = ratio >= threshold
    central_ids = [n for n, _ in top_nodes]

    if is_centralized:
        logger.warning(
            f"[!] Graph centralization detected: top-{top_n} nodes hold "
            f"{ratio:.0%} of edges ({top_degree_sum}/{total}). "
            f"Central nodes: {central_ids}. Rupture recommended on next traversal."
        )

    return is_centralized, central_ids, round(ratio, 4)


# ─── Main Entry Point ─────────────────────────────────────────────────────────

async def run_rhizome_builder(
    graph: RelationshipGraph,
    rupture: RuptureOutput,
) -> tuple[RelationshipGraph, RhizomePersistResult]:
    """
    1. Classify edges into constructive / critical / rhizomatic using LLM.
    2. Mark rupture nodes based on RuptureOutput.
    3. Optionally persist to Neo4j if configured.

    Returns updated RelationshipGraph and persistence result.
    """
    # Mark rupture nodes
    rupture_keywords = set(
        kw.lower() for kw in rupture.outside_view_entry_points
    )
    updated_nodes = []
    for node in graph.nodes:
        label_lower = node.label.lower()
        is_rupture = node.type == "rupture" or any(
            kw in label_lower for kw in rupture_keywords
        )
        axiom_dismantled = None
        if is_rupture and rupture.axiom_targets:
            axiom_dismantled = rupture.axiom_targets[0]

        updated_nodes.append(
            GraphNode(
                id=node.id,
                label=node.label,
                type="rupture" if is_rupture else node.type,
                importance=node.importance,
                description=node.description,
                is_rupture_node=is_rupture,
                axiom_dismantled=axiom_dismantled,
            )
        )

    # Classify edges
    classified_edges = await _classify_edges(graph.edges)

    updated_graph = RelationshipGraph(nodes=updated_nodes, edges=classified_edges)

    # Detect graph centralization before persistence
    is_centralized, central_ids, centralization_ratio = _detect_centralization(updated_graph)

    # Persist to Neo4j (if enabled)
    if settings.neo4j_enabled and settings.neo4j_uri:
        persist_result = await _persist_to_neo4j(updated_graph)
    else:
        persist_result = RhizomePersistResult(
            neo4j_enabled=False,
            message="Neo4j persistence disabled. Set NEO4J_ENABLED=true and NEO4J_URI to activate.",
        )

    # Attach centralization data to result
    persist_result.graph_centralized = is_centralized
    persist_result.central_node_ids = central_ids
    persist_result.centralization_ratio = centralization_ratio

    logger.info(f"Rhizome Builder: {persist_result.message}")
    return updated_graph, persist_result
